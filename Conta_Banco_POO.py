import textwrap
from abc import ABC, abstractmethod
from datetime import datetime


class Cliente:
    def __init__(self, endereco):
        self.endereco = endereco
        self.contas = []

    def realizar_transacao(self, conta, transacao):
        transacao.registrar(conta)

    def adicionar_conta(self, conta):
        self.contas.append(conta)


class PessoaFisica(Cliente):
    def __init__(self, nome, data_nascimento, cpf, endereco):
        super().__init__(endereco)
        self.nome = nome
        self.data_nascimento = data_nascimento
        self.cpf = cpf


class Conta:
    def __init__(self, numero, cliente):
        self._saldo = 0
        self._numero = numero
        self._agencia = "0001"
        self._cliente = cliente
        self._historico = Historico()

    @classmethod
    def nova_conta(cls, cliente, numero):
        return cls(numero, cliente)

    @property
    def saldo(self):
        return self._saldo

    @property
    def numero(self):
        return self._numero

    @property
    def agencia(self):
        return self._agencia

    @property
    def cliente(self):
        return self._cliente

    @property
    def historico(self):
        return self._historico

    def sacar(self, valor):
        saldo = self.saldo
        excedeu_saldo = valor > saldo

        if excedeu_saldo:
            print("\n@@@ Operação falhou! Você não tem saldo suficiente. @@@")

        elif valor > 0:
            self._saldo -= valor
            print("\n=== Saque realizado com sucesso! ===")
            return True

        else:
            print("\n@@@ Operação falhou! O valor informado é inválido. @@@")

        return False

    def depositar(self, valor):
        if valor > 0:
            self._saldo += valor
            print("\n=== Depósito realizado com sucesso! ===")
        else:
            print("\n@@@ Operação falhou! O valor informado é inválido. @@@")
            return False

        return True


class ContaCorrente(Conta):
    def __init__(self, numero, cliente, limite=500, limite_saques=3):
        super().__init__(numero, cliente)
        self._limite = limite
        self._limite_saques = limite_saques

    def sacar(self, valor):
        numero_saques = len(
            [transacao for transacao in self.historico.transacoes if transacao["tipo"] == Saque.__name__]
        )

        excedeu_limite = valor > self._limite
        excedeu_saques = numero_saques >= self._limite_saques

        if excedeu_limite:
            print("\n@@@ Operação falhou! O valor do saque excede o limite. @@@")

        elif excedeu_saques:
            print("\n@@@ Operação falhou! Número máximo de saques excedido. @@@")

        else:
            return super().sacar(valor)

        return False

    def __str__(self):
        return f"""\
            Agência:\t{self.agencia}
            C/C:\t\t{self.numero}
            Titular:\t{self.cliente.nome}
        """


class Historico:
    def __init__(self):
        self._transacoes = []

    @property
    def transacoes(self):
        return self._transacoes

    def adicionar_transacao(self, transacao):
        self._transacoes.append(
            {
                "tipo": transacao.__class__.__name__,
                "valor": transacao.valor,
                "data": datetime.now().strftime("%d-%m-%Y %H:%M:%s"),
            }
        )


class Transacao(ABC):
    @property
    @abstractmethod
    def valor(self):
        pass

    @classmethod
    @abstractmethod
    def registrar(cls, conta):
        pass


class Saque(Transacao):
    def __init__(self, valor):
        self._valor = valor

    @property
    def valor(self):
        return self._valor

    def registrar(self, conta):
        sucesso_transacao = conta.sacar(self.valor)

        if sucesso_transacao:
            conta.historico.adicionar_transacao(self)


class Deposito(Transacao):
    def __init__(self, valor):
        self._valor = valor

    @property
    def valor(self):
        return self._valor

    def registrar(self, conta):
        sucesso_transacao = conta.depositar(self.valor)

        if sucesso_transacao:
            conta.historico.adicionar_transacao(self)


class CartaoCredito:
    def __init__(self, limite, cliente):
        self.limite = limite
        self.cliente = cliente
        self.saldo_utilizado = 0

    def solicitar_cartao(self):
        print(f"\n=== Cartão de crédito solicitado com sucesso! ===")
        print(f"Titular: {self.cliente.nome}")
        print(f"Limite aprovado: R$ {self.limite:.2f}")

    def usar_cartao(self, valor):
        if valor > (self.limite - self.saldo_utilizado):
            print("\n@@@ Operação falhou! Valor excede o limite disponível. @@@")
            return False
        self.saldo_utilizado += valor
        print(f"\n=== Compra de R$ {valor:.2f} realizada com sucesso! ===")
        return True

    def exibir_fatura(self):
        print("\n=== Fatura do Cartão de Crédito ===")
        print(f"Titular: {self.cliente.nome}")
        print(f"Limite total: R$ {self.limite:.2f}")
        print(f"Saldo utilizado: R$ {self.saldo_utilizado:.2f}")
        print(f"Limite disponível: R$ {self.limite - self.saldo_utilizado:.2f}")


class Emprestimo:
    def __init__(self, valor, taxa_juros, prazo, cliente):
        self.valor = valor
        self.taxa_juros = taxa_juros  # Taxa de juros anual em porcentagem
        self.prazo = prazo  # Prazo em meses
        self.cliente = cliente

    def calcular_parcelas(self):
        taxa_mensal = self.taxa_juros / 12 / 100
        parcela = self.valor * (taxa_mensal * (1 + taxa_mensal) ** self.prazo) / ((1 + taxa_mensal) ** self.prazo - 1)
        return parcela

    def simular_emprestimo(self):
        parcela = self.calcular_parcelas()
        total_pago = parcela * self.prazo
        juros_totais = total_pago - self.valor

        print("\n=== Simulação de Empréstimo ===")
        print(f"Titular: {self.cliente.nome}")
        print(f"Valor solicitado: R$ {self.valor:.2f}")
        print(f"Taxa de juros anual: {self.taxa_juros:.2f}%")
        print(f"Prazo: {self.prazo} meses")
        print(f"Valor da parcela: R$ {parcela:.2f}")
        print(f"Total a pagar: R$ {total_pago:.2f}")
        print(f"Juros totais: R$ {juros_totais:.2f}")


